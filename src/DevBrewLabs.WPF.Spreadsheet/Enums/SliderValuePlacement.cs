namespace DevBrewLabs.WPF.Spreadsheet.Enums
{
    /// <summary>
    /// Specifies where the numeric value label is positioned relative to the slider track.
    /// </summary>
    public enum SliderValuePlacement
    {
        /// <summary>
        /// Do not display the numeric value label.
        /// </summary>
        None,

        /// <summary>
        /// Display the numeric value label to the right of the slider track.
        /// </summary>
        Right,

        /// <summary>
        /// Display the numeric value label to the left of the slider track.
        /// </summary>
        Left
    }
}
